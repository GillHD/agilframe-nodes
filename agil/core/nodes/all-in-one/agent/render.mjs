/**
 * Renders the process configuration for the all-in-one node:
 *
 *   - LiveKit is configured through `LIVEKIT_CONFIG` (YAML body) and
 *     `LIVEKIT_KEYS` (API key/secret pair) — no config file is written, so the
 *     SFU secret never lands on disk.
 *   - coturn has no equivalent environment interface, so its configuration is
 *     written to `$NODE_RUNTIME_DIR/turnserver.conf` with mode 0600 (tmpfs in
 *     the compose file). Passing the credential on the command line would
 *     expose it through `ps`/`/proc`.
 *
 * Both renderers are pure functions so the tests can assert the exact YAML,
 * coturn options and media plan without spawning a server.
 */

import path from 'node:path';

import { ConfigError, detectHostIpv4 } from './config.mjs';

/** YAML double-quoted scalar (JSON string escaping is valid YAML). */
function yamlString(value) {
  return JSON.stringify(String(value));
}

/**
 * LiveKit server configuration. Ports mirror `agil/core/deploy/livekit/livekit.yaml`
 * (7880 signalling, 7881 RTC/TCP, 50000-50100 RTC/UDP) so an operator can move
 * between the standalone scaffold and this image without changing firewalls.
 */
export function renderLiveKitConfig(config) {
  const sfu = config.sfu;
  if (!sfu.enabled) return '';
  const lines = [
    '# Generated by the AGIL all-in-one node agent. Do not edit inside the container.',
    `port: ${sfu.port}`,
    'rtc:',
    `  tcp_port: ${sfu.tcpPort}`,
  ];
  if (sfu.udpMuxPort > 0) {
    // LiveKit enables the single-port UDP mux only when no port range is set
    // ("port_range_start & end must not be set for this config to take effect").
    lines.push(`  udp_port: ${sfu.udpMuxPort}`);
  } else {
    lines.push(`  port_range_start: ${sfu.udpMinPort}`);
    lines.push(`  port_range_end: ${sfu.udpMaxPort}`);
  }
  if (sfu.nodeIp) {
    lines.push(`  node_ip: ${yamlString(sfu.nodeIp)}`);
    lines.push('  use_external_ip: false');
  } else {
    // Default: let LiveKit discover the public address with STUN. Behind 1:1 NAT
    // with UDP egress blocked this can fail; set SFU_NODE_IP then.
    lines.push(`  use_external_ip: ${sfu.useExternalIp ? 'true' : 'false'}`);
  }

  const { redis } = sfu;
  if (redis) {
    lines.push('redis:');
    lines.push(`  address: ${yamlString(redis.address)}`);
    if (redis.username) lines.push(`  username: ${yamlString(redis.username)}`);
    if (redis.password) lines.push(`  password: ${yamlString(redis.password)}`);
    if (redis.db !== undefined && Number.isInteger(redis.db)) lines.push(`  db: ${redis.db}`);
    if (redis.useTls) lines.push('  use_tls: true');
  }

  if (sfu.rtmpIngressBaseUrl) {
    lines.push('ingress:');
    lines.push(`  rtmp_base_url: ${yamlString(sfu.rtmpIngressBaseUrl)}`);
  }

  if (sfu.metricsPort > 0) {
    // LiveKit has no per-listener bind option for Prometheus (strict config:
    // `prometheus.bind_addresses` is an unknown field and aborts startup), so
    // this listener is bound on all host interfaces. With host networking the
    // firewall/security group must close SFU_METRICS_PORT, or set it to 0.
    lines.push('prometheus:');
    lines.push(`  port: ${sfu.metricsPort}`);
  }

  lines.push('logging:');
  lines.push(`  level: ${yamlString(sfu.logLevel)}`);
  lines.push('  json: true');
  lines.push('');
  return `${lines.join('\n')}`;
}

/** `LIVEKIT_KEYS` value: `<api-key>: <api-secret>` (both validated). */
export function renderLiveKitKeys(config) {
  return `${config.sfu.apiKey}: ${config.sfu.apiSecret}`;
}

/**
 * coturn configuration. Written to a 0600 file, not passed via argv.
 *
 * `turn`: static or time-limited credentials + relay range.
 * `stun`: STUN-only, no authentication and no relay allocation, so a `stun`
 *         node can run without a TURN password or relay ports.
 */
export function renderTurnConfig(config) {
  const turn = config.turn;
  const enabled = turn.enabled || turn.stunOnly;
  if (!enabled) return '';
  const lines = [
    '# Generated by the AGIL all-in-one node agent. Contains the TURN credential: keep mode 0600.',
    'log-file=stdout',
    'no-cli',
    // The agent reaps coturn itself; a pid file in the tmpfs runtime dir keeps
    // coturn from trying to write /var/run/turnserver.pid on a read-only root.
    `pidfile=${path.posix.join(config.runtimeDir, 'turnserver.pid')}`,
    // Coturn opens its SQLite user database even with users in the config.
    `userdb=${path.posix.join(config.runtimeDir, 'turn-userdb.sqlite')}`,
    'no-multicast-peers',
    // Do not let a TURN allocation reach loopback services on the node host.
    'denied-peer-ip=127.0.0.0-127.255.255.255',
    'denied-peer-ip=::1',
    'fingerprint',
    `listening-port=${turn.port}`,
  ];
  if (turn.listenIp) lines.push(`listening-ip=${turn.listenIp}`);

  if (turn.stunOnly) {
    lines.push('stun-only');
    lines.push('no-auth');
  } else {
    lines.push(`realm=${turn.realm}`);
    if (turn.staticAuthSecret) {
      lines.push('use-auth-secret', `static-auth-secret=${turn.staticAuthSecret}`);
    } else {
      lines.push('lt-cred-mech', `user=${turn.user}:${turn.password}`);
    }
    lines.push(`min-port=${turn.minPort}`);
    lines.push(`max-port=${turn.maxPort}`);
    lines.push(`total-quota=${turn.totalQuota}`);
    lines.push(`user-quota=${turn.userQuota}`);
    if (turn.externalIp) {
      // 1:1 NAT (cloud VM): advertise the public address for the relay while
      // coturn still binds the private interface.
      lines.push(
        `external-ip=${turn.externalIp}${turn.internalIp ? `/${turn.internalIp}` : ''}`,
      );
    }
  }

  if (turn.tls) {
    lines.push(`tls-listening-port=${turn.tlsPort}`);
    lines.push('no-tlsv1');
    lines.push('no-tlsv1_1');
    lines.push(`cert=${turn.cert}`);
    lines.push(`pkey=${turn.pkey}`);
  } else {
    lines.push('no-tls');
    lines.push('no-dtls');
  }
  lines.push('');
  return `${lines.join('\n')}`;
}

export function turnConfigPath(config) {
  // Container paths are POSIX even when the pure renderer is unit-tested on
  // Windows, so use path.posix instead of the host separator.
  return path.posix.join(config.runtimeDir, 'turnserver.conf');
}

/**
 * The processes this configuration asks for. `files` are written by the agent
 * before the process starts; `env` is merged into a scrubbed child environment.
 */
export function mediaPlan(config) {
  const plan = [];
  if (config.sfu.enabled && !config.sfu.externalOrigin) {
    plan.push({
      name: 'livekit',
      kind: 'sfu',
      command: config.sfu.bin,
      args: [...config.sfu.extraArgs],
      env: {
        LIVEKIT_CONFIG: renderLiveKitConfig(config),
        LIVEKIT_KEYS: renderLiveKitKeys(config),
      },
      files: [],
      // Non-secret values referenced in logs/health output.
      port: config.sfu.port,
      probe: { protocol: 'http', host: '127.0.0.1', port: config.sfu.port },
    });
  }
  if (config.turn.enabled || config.turn.stunOnly) {
    const configPath = turnConfigPath(config);
    plan.push({
      name: 'turnserver',
      kind: config.turn.enabled ? 'turn' : 'stun',
      command: config.turn.bin,
      args: [...config.turn.extraArgs, '-c', configPath],
      env: {},
      files: [{ path: configPath, mode: 0o600, content: renderTurnConfig(config) }],
      port: config.turn.port,
      probe: {
        protocol: 'stun', host: config.turn.listenIp || detectHostIpv4() || '127.0.0.1', port: config.turn.port,
        ...(config.turn.tls ? { tlsPort: config.turn.tlsPort } : {}),
        ...(config.turn.tlsHostname ? { tlsHostname: config.turn.tlsHostname } : {}),
      },
    });
  }
  return plan;
}
